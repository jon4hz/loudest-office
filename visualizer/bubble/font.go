// unknownGlyph is a filled 5x7 box outline, drawn for any rune with no glyph.
var unknownGlyph = [7]uint8{0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f}

// folds are the letters NFD leaves whole.
var folds = strings.NewReplacer("ß", "SS", "ø", "o", "Ø", "O", "æ", "ae", "Æ", "AE",
	"œ", "oe", "Œ", "OE", "ł", "l", "Ł", "L", "’", "'")

// fold spells s with the letters the font has: decomposed, without the
// combining marks.
func fold(s string) string {
	return strings.Map(func(r rune) rune {
		if unicode.Is(unicode.Mn, r) {
			return -1
		}
		return r
	}, norm.NFD.String(folds.Replace(s)))
}

// DrawText draws s with the top-left pixel of its first glyph at x,y, in
// colour c, scaled up by scale. Each glyph advances 6*scale pixels. Pixels
// that land outside frame are skipped silently; zero-alpha colours are the
// caller's business. Lowercase folds to uppercase; accented letters fold to
// their base letter. A rune with no glyph draws unknownGlyph instead.
func DrawText(frame [][]color.RGBA, x, y int, s string, c color.RGBA, scale int) {
	h := len(frame)
	cx := x
	for _, r := range fold(s) {
		g, ok := glyphs[unicode.ToUpper(r)]
		if !ok {
			g = unknownGlyph
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if g[row]&(1<<(4-col)) == 0 {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					py := y + row*scale + sy
					if py < 0 || py >= h {
						continue
					}
					w := len(frame[py])
					for sx := 0; sx < scale; sx++ {
						px := cx + col*scale + sx
						if px < 0 || px >= w {
							continue
						}
						frame[py][px] = c
					}
				}
			}
		}
		cx += 6 * scale
	}
}

// TextWidth is the pixel width of s at scale: 6*scale per rune, minus the
// trailing gap after the last glyph.
func TextWidth(s string, scale int) int {
	n := utf8.RuneCountInString(fold(s))
	if n == 0 {
		return 0
	}
	return n*6*scale - scale
}
